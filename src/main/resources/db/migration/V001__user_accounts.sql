CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(80) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_preferences (
    user_id BIGINT PRIMARY KEY,
    theme VARCHAR(10) NOT NULL DEFAULT 'dark',
    time_of_day VARCHAR(20) NOT NULL DEFAULT 'Anytime',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_preferences_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

ALTER TABLE habits ADD COLUMN IF NOT EXISTS user_id BIGINT;
ALTER TABLE habits ADD CONSTRAINT fk_habit_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE habits ADD CONSTRAINT uk_habit_id_user UNIQUE (id, user_id);
CREATE INDEX IF NOT EXISTS ix_habit_user_created ON habits(user_id, created_at DESC);

ALTER TABLE habit_checkins ADD COLUMN IF NOT EXISTS user_id BIGINT;
UPDATE habit_checkins SET user_id = (SELECT user_id FROM habits WHERE habits.id = habit_checkins.habit_id) WHERE user_id IS NULL;
ALTER TABLE habit_checkins ADD CONSTRAINT fk_checkin_habit_owner FOREIGN KEY (habit_id, user_id) REFERENCES habits(id, user_id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS ix_checkin_user_date ON habit_checkins(user_id, checkin_date);

CREATE TABLE IF NOT EXISTS habit_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    habit_id BIGINT NOT NULL,
    note_date DATE NOT NULL,
    note VARCHAR(500) NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_note_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_note_habit_owner FOREIGN KEY (habit_id, user_id) REFERENCES habits(id, user_id) ON DELETE CASCADE,
    CONSTRAINT uk_note_user_habit_date UNIQUE (user_id, habit_id, note_date)
);

CREATE TABLE IF NOT EXISTS focus_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    habit_id BIGINT,
    started_at TIMESTAMP NOT NULL,
    duration_minutes INTEGER NOT NULL,
    CONSTRAINT fk_focus_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_focus_habit_owner FOREIGN KEY (habit_id, user_id) REFERENCES habits(id, user_id) ON DELETE CASCADE,
    CONSTRAINT ck_focus_minutes CHECK (duration_minutes BETWEEN 1 AND 1440)
);

CREATE INDEX IF NOT EXISTS ix_focus_user_started ON focus_sessions(user_id, started_at);
